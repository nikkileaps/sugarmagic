/** Clamp a meter value to the renderable 0..1 range. NaN clamps to 0. */
export function clampRatio(value: number): number {
  if (!Number.isFinite(value)) return 0;
  return Math.min(1, Math.max(0, value));
}

/**
 * Panel height (source pixels) that gives the content area
 * `contentSourceHeight` source pixels of room on the given frame.
 */
export function frameHeightForContent(
  geometry: FrameGeometry,
  contentSourceHeight: number
): number {
  return Math.max(
    geometry.naturalHeight,
    Math.ceil(contentSourceHeight) +
      geometry.contentInsets.top +
      geometry.contentInsets.bottom
  );
}
