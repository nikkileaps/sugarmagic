/**
 * packages/runtime-core/src/framed-panel/geometry.ts
 *
 * Purpose: Source-pixel geometry for the ornate framed panels. Two painted
 *   sheets share one assembly scheme: the CASTER frame (top rail carries the
 *   battery pill, center medallion and resonance pill) and the PLAIN frame
 *   (bare rails, used by the inventory list). Every rectangle is a cut from
 *   its sheet; the DOM assembler in ./index.ts positions the cuts, and tests
 *   assert the cuts stay contiguous and inside their sheet.
 *
 * Coordinates are SOURCE pixels of each sheet. A frame's outer edge starts
 * at its `origin`, so panel-local coordinates are source minus origin. The
 * DOM layer multiplies by a display scale.
 *
 * Slices come in two kinds:
 *   - fixed pieces, shown via background-position into the full sheet;
 *   - repeating/stretching pieces (side rails, plain rail strips, parchment
 *     tile), which need their own image files because CSS tiles a whole
 *     image, never a sheet sub-region. These are the keys of
 *     REPEATING_SLICE_ART.
 *
 * Exports:
 *   - FrameGeometry, FrameSlice, MeterRect, REPEATING_SLICE_ART
 *   - CASTER_FRAME_GEOMETRY, PLAIN_FRAME_GEOMETRY, MEDALLION_CIRCLE
 *   - clampRatio, frameHeightForContent
 *
 * Relationships:
 *   - Pure data and math. No DOM. ./index.ts renders it.
 *   - The cuts were settled in docs/prototypes/caster-frame.html and
 *     plain-frame.html; the repeating slice files are generated by
 *     docs/prototypes/caster-frame-slices.py from the same tables.
 *
 * Status: active
 */

/** One rectangle cut from a sheet, in source pixels. */
export interface FrameSlice {
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}

export interface MeterRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface FrameBandSegment {
  slice: string;
  stretch: boolean;
}

export interface FrameGeometry {
  sheet: { width: number; height: number };
  /** The frame's outer wood edge inside the sheet (the rest is margin). */
  origin: { x: number; y: number };
  /** Panel-local frame width in source pixels. */
  frameWidth: number;
  /** Panel-local frame height in source pixels at the sheet's natural size. */
  naturalHeight: number;
  /** Corner piece height; the side rails run between the corners. */
  cornerHeight: number;
  topBandHeight: number;
  bottomBandHeight: number;
  /**
   * Interior insets of the usable content area on the parchment,
   * panel-local source pixels: clear of any hardware overhang and the
   * pinstripe border.
   */
  contentInsets: { top: number; right: number; bottom: number; left: number };
  slices: Record<string, FrameSlice>;
  /**
   * Top band composition, left to right. Stretch entries scale their strip
   * to the flexed width (never tiled) and collapse to zero when the fixed
   * segments already sum to the frame width.
   */
  topBand: ReadonlyArray<FrameBandSegment>;
  bottomBand: ReadonlyArray<FrameBandSegment>;
  /** Live meter overlays covering painted pill troughs; null = no meters. */
  meters: { battery: MeterRect; resonance: MeterRect } | null;
}

